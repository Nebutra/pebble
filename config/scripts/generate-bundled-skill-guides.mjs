import { createHash } from 'node:crypto'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const repoRoot = path.resolve(import.meta.dirname, '../..')
const appVersion = JSON.parse(await readFile(path.join(repoRoot, 'package.json'), 'utf8')).version
const upstreamRef = '58ef46d2522da100f1b49cac25413f0b42290b46'

export const skillNames = [
  'computer-use',
  'linear-tickets',
  'orchestration',
  'pebble-cli',
  'pebble-emulator',
  'pebble-emulator-android',
  'pebble-linear',
  'pebble-per-workspace-env'
]

function normalizeMarkdown(value) {
  return `${value.replaceAll('\r\n', '\n').trimEnd()}\n`
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex')
}

function parseFrontmatter(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---\n/)
  if (!match) {
    throw new Error('Skill guide is missing YAML frontmatter.')
  }
  const name = match[1].match(/^name:\s*(.+)$/m)?.[1]?.trim()
  const descriptionLines = match[1].match(/description:\s*>-?\n([\s\S]*?)(?:\n[^\s]|$)/)?.[1]
  const description = descriptionLines
    ?.split('\n')
    .map((line) => line.trim())
    .join(' ')
    .trim()
  if (!name || !description) {
    throw new Error('Skill guide frontmatter is incomplete.')
  }
  return { name, description }
}

function stubFor(name, description) {
  return normalizeMarkdown(`---
name: ${name}
description: >-
  ${description}
---

# ${name}

This is a discovery stub. Pebble keeps the full guide with the installed CLI so
the instructions cannot drift from the binary that will execute them.

Resolve the executable once for this session. Use the value of
\`PEBBLE_CLI_COMMAND\` when it is set, use \`pebble-dev\` inside a Pebble source
checkout, and otherwise use \`pebble\`. Reuse that executable for every command;
do not silently fall through to another build after an error.

Before using this skill, run:

\`\`\`text
PEBBLE skills get ${name}
\`\`\`

Here \`PEBBLE\` is a placeholder for the executable selected above, not a shell
variable. Read the returned version-matched guide before choosing subcommands or
flags, and prefer \`--json\` for agent-driven calls when the command supports it.

If the selected binary explicitly reports that \`skills get\` is unknown, report
that the installed Pebble predates bundled guides. Do not guess a newer command
surface or switch binaries automatically.
`)
}

function goString(value) {
  return JSON.stringify(value)
}

function generatedGo(guides) {
  const entries = guides
    .map(
      ({ name, content, revision }) =>
        `\t${goString(name)}: {Revision: ${revision}, Content: ${goString(content)}},`
    )
    .join('\n')
  return `// Code generated by config/scripts/generate-bundled-skill-guides.mjs; DO NOT EDIT.
package main

type bundledSkillGuide struct {
\tRevision int
\tContent string
}

const bundledSkillAppVersion = ${goString(appVersion)}

var bundledSkillGuides = map[string]bundledSkillGuide{
${entries}
}
`
}

async function readGuides({ bootstrap }) {
  const guides = []
  await mkdir(path.join(repoRoot, 'skill-guides'), { recursive: true })
  for (const name of skillNames) {
    const guidePath = path.join(repoRoot, 'skill-guides', `${name}.md`)
    let content
    try {
      content = await readFile(guidePath, 'utf8')
    } catch (error) {
      if (!bootstrap || error?.code !== 'ENOENT') {
        throw error
      }
      content = await readFile(path.join(repoRoot, 'skills', name, 'SKILL.md'), 'utf8')
      await writeFile(guidePath, normalizeMarkdown(content))
    }
    content = normalizeMarkdown(content)
    const metadata = parseFrontmatter(content)
    if (metadata.name !== name) {
      throw new Error(`${guidePath} declares ${metadata.name}.`)
    }
    guides.push({ name, content, description: metadata.description, revision: 1 })
  }
  return guides
}

export async function buildArtifacts(options = {}) {
  const guides = await readGuides(options)
  const currentManifest = {
    schemaVersion: 1,
    appVersion,
    upstreamRef,
    skills: guides.map(({ name, content, revision }) => ({
      name,
      releaseRevision: revision,
      sha256: digest(content),
      size: Buffer.byteLength(content)
    }))
  }
  const releaseMapping = {
    schemaVersion: 1,
    releases: [
      {
        appVersion,
        skills: Object.fromEntries(guides.map(({ name, revision }) => [name, revision]))
      }
    ]
  }
  const snapshotRegistry = {
    schemaVersion: 1,
    skills: Object.fromEntries(
      guides.map(({ name, content, revision }) => [
        name,
        [
          {
            releaseRevision: revision,
            upstreamRef,
            sha256: digest(content),
            size: Buffer.byteLength(content)
          }
        ]
      ])
    )
  }
  return {
    guides,
    files: new Map([
      ['resources/skills/current-manifest.json', `${JSON.stringify(currentManifest, null, 2)}\n`],
      ['resources/skills/release-mapping.json', `${JSON.stringify(releaseMapping, null, 2)}\n`],
      ['resources/skills/snapshot-registry.json', `${JSON.stringify(snapshotRegistry, null, 2)}\n`],
      ['runtime/go/cmd/pebble-control/bundled_skill_guides_generated.go', generatedGo(guides)],
      ...guides.map(({ name, description }) => [
        `skills/${name}/SKILL.md`,
        stubFor(name, description)
      ])
    ])
  }
}

async function writeArtifacts(artifacts) {
  for (const [relativePath, content] of artifacts.files) {
    const target = path.join(repoRoot, relativePath)
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, content)
  }
}

async function verifyArtifacts(artifacts) {
  const stale = []
  for (const [relativePath, expected] of artifacts.files) {
    const actual = await readFile(path.join(repoRoot, relativePath), 'utf8').catch(() => null)
    if (actual !== expected) {
      stale.push(relativePath)
    }
  }
  if (stale.length > 0) {
    throw new Error(`Generated bundled skill guides are stale:\n${stale.join('\n')}`)
  }
}

async function main() {
  const write = process.argv.includes('--write')
  const bootstrap = process.argv.includes('--bootstrap')
  const artifacts = await buildArtifacts({ bootstrap })
  await (write ? writeArtifacts(artifacts) : verifyArtifacts(artifacts))
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
}
